/** Reads one fixture file's raw text off disk, by its path relative to `FIXTURE_ROOT`. */
function readFixtureFile(relPath) {
  return readFileSync(path.join(FIXTURE_ROOT, relPath), "utf8");
}

/**
 * Builds `{ _git, _readFile }` seams over the WHOLE frozen fixture: `_git`'s scripted
 * `ls-files` answer lists all 25 paths (mirroring `DECISION_CORPUS_ARGV`'s live single-call
 * enumeration, TSPEC §3.1), and `_readFile` resolves each of those same 25 paths to its frozen
 * fixture content. `gatherDecisionCorpus` is what narrows this down to project-level plus one
 * feature's own directory — this helper hands it the same universe `_git` would return live.
 */
function buildFixtureSeams(paths = ALL_FIXTURE_PATHS) {
  const files = {};
  for (const relPath of paths) files[relPath] = readFixtureFile(relPath);
  const stdout = paths.join("\n");
  return makeDecisionLedgerSeams({
    _git: makeGitDouble({ "ls-files": { ok: true, stdout } }),
    _readFile: makeReadFileDouble(files),
  });
}

/** Builds the `CorpusEntry[]` shape `selectDecisions` takes directly, bypassing
 * `gatherDecisionCorpus`'s feature-directory resolution — used by the whole-fixture and
 * `M-6b`-slice DEC-DECLEDGER-13 assertions, which span more than one feature directory at once. */
function entriesFor(paths) {
  return paths.map((relPath) => ({
    path: relPath,
    text: readFixtureFile(relPath),
    readOk: true,
  }));
}

