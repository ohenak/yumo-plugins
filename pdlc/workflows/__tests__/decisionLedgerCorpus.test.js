describe("T-17: AT-02 — citation round-trip resolves back at its own source (TSPEC §4.3)", () => {
  test("every rendered line's [sourcePath § id] citation resolves, via the SAME _readFile double, to a heading whose captured statement matches the rendered statement — no DecisionRecord field read", async () => {
    const { gatherDecisionCorpus, selectDecisions, renderDecisionLedgerBlock, DECISION_LEDGER_DEFAULTS } =
      await import(DEV_MODULE_PATH);
    const seams = buildFixtureSeams();
    const corpus = await gatherDecisionCorpus({ feature: "pdlc-advisory-wave-gate", ...seams });
    expect(corpus.unlistable).toBe(false);
    const { selected } = selectDecisions({
      entries: corpus.entries,
      feature: "pdlc-advisory-wave-gate",
      thresholds: DECISION_LEDGER_DEFAULTS,
    });

    const block = renderDecisionLedgerBlock({ selected });
    // The rendered block's index lines only — never the framing — carry a citation bracket.
    const renderedLines = block
      .split("\n")
      .filter((line) => CITATION_RE.test(line));
    expect(renderedLines.length).toBe(PLUS_AWG_LINE_COUNT);

    for (const line of renderedLines) {
      // Parse sourcePath and id OUT OF THE STRING — no `.sourcePath`/`.id` field is read here.
      const citationMatch = CITATION_RE.exec(line);
      expect(citationMatch).not.toBeNull();
      const [, parsedSourcePath, parsedId] = citationMatch;

      // Parse the rendered statement out of the string too: strip the trailing citation and its
      // leading "  " separator, then the leading "{id} — " prefix.
      const withoutCitation = line.slice(0, line.length - citationMatch[0].length).replace(/ {2}$/, "");
      const idPrefix = `${parsedId} — `;
      expect(withoutCitation.startsWith(idPrefix)).toBe(true);
      const parsedStatement = withoutCitation.slice(idPrefix.length);

      // Re-open the fixture path through the SAME `_readFile` double `gatherDecisionCorpus` used.
      const reopenedText = seams._readFile(parsedSourcePath);
      expect(reopenedText).not.toBeNull();

      // Find the heading whose captured id equals the parsed id, via this file's OWN model
      // regex — never `DECISION_HEADING_RE`, never `recogniseDecisionRecords`.
      const headingLines = reopenedText.split(/\r\n|\r|\n/);
      let matchedStatement = null;
      for (const headingLine of headingLines) {
        const headingMatch = MODEL_HEADING_RE.exec(headingLine);
        if (headingMatch && headingMatch[1] === parsedId) {
          matchedStatement = headingMatch[2]; // last-wins: keep overwriting on later matches
        }
      }
      expect(matchedStatement).not.toBeNull();
      expect(matchedStatement).toBe(parsedStatement);
    }
  });
});

describe("T-17: AT-18 — cross-file precedence over a synthetic two-file corpus (TSPEC §3.4, FSPEC O-5)", () => {
  // A synthetic (never disk-fixture) two-file corpus: the SAME id recorded once in a
  // project-level file and once in a feature-level file, with DIFFERENT statements, so the two
  // origins are distinguishable in the assertion.
  const SHARED_ID = "DEC-SYNTH-01";
  const PROJECT_STATEMENT = "the project-level statement, which must be the one rendered";
  const FEATURE_STATEMENT = "the feature-level statement, which must never appear in the block";
  const SYNTH_PROJECT_PATH = "docs/_decisions/DECISIONS-synth-o5.md";
  const SYNTH_FEATURE_PATH = "docs/pdlc-synth-o5/DECISIONS-pdlc-synth-o5.md";

  function synthEntries() {
    return [
      {
        path: SYNTH_PROJECT_PATH,
        text: `## ${SHARED_ID}: ${PROJECT_STATEMENT}\n`,
        readOk: true,
      },
      {
        path: SYNTH_FEATURE_PATH,
        text: `### ${SHARED_ID}: ${FEATURE_STATEMENT}\n`,
        readOk: true,
      },
    ];
  }

  test("exactly one line carries the shared id, and its statement/sourcePath/origin are the PROJECT-level record's (positive conjunct, not cardinality alone)", async () => {
    const { selectDecisions, renderDecisionLedgerBlock, DECISION_LEDGER_DEFAULTS } = await import(
      DEV_MODULE_PATH
    );
    const result = selectDecisions({
      entries: synthEntries(),
      feature: "pdlc-synth-o5",
      thresholds: DECISION_LEDGER_DEFAULTS,
    });

    // Cardinality alone would pass under the REJECTED feature-wins rule too (TSPEC §3.4) — this
    // is why the statement/sourcePath/origin conjuncts below are asserted as well, not instead.
    const matches = result.selected.filter((r) => r.id === SHARED_ID);
    expect(matches).toHaveLength(1);
    const [record] = matches;
    expect(record.statement).toBe(PROJECT_STATEMENT);
    expect(record.sourcePath).toBe(SYNTH_PROJECT_PATH);
    expect(record.origin).toBe("project");

    const block = renderDecisionLedgerBlock({ selected: result.selected });
    expect(block).toContain(PROJECT_STATEMENT);
    // The feature-level statement is absent from the WHOLE rendered block, not merely absent
    // from the one line naming the shared id — swapping precedence direction would leave
    // cardinality green while reddening exactly this conjunct.
    expect(block).not.toContain(FEATURE_STATEMENT);
  });
});

