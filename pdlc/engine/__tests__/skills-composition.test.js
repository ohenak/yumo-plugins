// ── PROP-SKILL-13 / AT-ENG-25 — EC-SKILL-4, integration ───────────────────────
//
// "A plugin upgraded mid-run must not change the run: it continues against
// the version the handshake approved, and a version change is discovered by
// the next run's handshake." `pluginRoot` is resolved once, at startup, and
// closed over by the adapter for its whole lifetime (adapter.mjs: `pluginRoot`
// constructor arg, never re-resolved by `_agent`/`skillTextFor`) — this proves
// that structurally: a fake fs that would resolve a NEWER version if asked
// again never gets asked again, so every dispatch across the run keeps
// reading the handshake-approved root.
test("EC-SKILL-4: a plugin upgraded mid-run does not change what an in-flight run dispatches", async () => {
  const v1Root = "/plugin/cache/pdlc/0.1.0";
  const v2Root = "/plugin/cache/pdlc/0.2.0";
  const v1File = path.join(v1Root, "skills", "pm-author", "SKILL.md");
  const v2File = path.join(v2Root, "skills", "pm-author", "SKILL.md");

  // The "upgrade": v2 appears on disk mid-run, alongside v1 (both readable) —
  // the handshake already approved v1, so nothing should ever read v2.
  const reads = [];
  const fs = {
    existsSync: (p) => p === v1File || p === v2File,
    readFileSync: (p) => {
      reads.push(p);
      if (p === v1File) return "# pm-author v1\n\nAuthor the REQ.";
      if (p === v2File) return "# pm-author v2 — UPGRADED\n\nAuthor the REQ, differently.";
      const err = new Error(`ENOENT: ${p}`);
      err.code = "ENOENT";
      throw err;
    },
  };
  const transport = { calls: [], dispatch: async function (prompt, opts) { this.calls.push({ prompt, opts }); return { text: "x" }; } };
  const adapter = createAdapter({
    transport,
    pluginRoot: v1Root, // the version the C-10 handshake approved at startup
    log: () => {},
    loadSkillFn: (root, name) => loadSkill(root, name, { fs }),
  });

  await adapter._agent("pm-author", "Write REQ, draft 1.");
  // "Upgrade" happens here, mid-run — nothing in the adapter re-resolves the root.
  await adapter._agent("pm-author", "Write REQ, draft 2.");

  assert.ok(reads.every((p) => p === v1File), `every read must stay on the handshake-approved root; saw: ${reads.join(", ")}`);
  for (const call of transport.calls) {
    assert.ok(call.prompt.includes("pm-author v1"), "every dispatch this run must carry v1 text");
    assert.equal(call.prompt.includes("UPGRADED"), false, "no dispatch this run may see the upgraded text");
  }
});
