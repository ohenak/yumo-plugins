test("EC-RUN-1: the whole plugin tree removed mid-run is its own fixture, distinct from a single missing file", async () => {
  // Two skills share one adapter/run: the first dispatch succeeds while the
  // tree is intact, then the WHOLE tree (not just one file) goes missing
  // before the second, uncached skill is dispatched.
  const pmAuthor = path.join("/plugin", "skills", "pm-author", "SKILL.md");
  const seAuthor = path.join("/plugin", "skills", "se-author", "SKILL.md");
  let treeRemoved = false;
  const fs = {
    existsSync: (p) => !treeRemoved && (p === pmAuthor || p === seAuthor),
    readFileSync: (p) => {
      if (treeRemoved) {
        const err = new Error(`ENOENT: no such file or directory, open '${p}'`);
        err.code = "ENOENT";
        throw err;
      }
      if (p === pmAuthor) return "# pm-author\n\nAuthor the REQ.";
      if (p === seAuthor) return "# se-author\n\nAuthor the TSPEC.";
      const err = new Error(`ENOENT: ${p}`);
      err.code = "ENOENT";
      throw err;
    },
  };
  const transport = { calls: [], dispatch: async function (prompt, opts) { this.calls.push({ prompt, opts }); return { text: "x" }; } };
  const adapter = createAdapter({
    transport,
    pluginRoot: "/plugin",
    log: () => {},
    loadSkillFn: (root, name) => loadSkill(root, name, { fs }),
  });
  await adapter._agent("pm-author", "Write REQ.");
  assert.equal(transport.calls.length, 1, "the first dispatch, tree intact, must succeed");

  treeRemoved = true; // the whole plugin tree vanishes while the run is in flight
  await assert.rejects(() => adapter._agent("se-author", "Write TSPEC."), (err) => {
    assert.match(err.message, /se-author/);
    return true;
  });
  assert.equal(transport.calls.length, 1, "no dispatch may proceed once the plugin tree is gone");
});

